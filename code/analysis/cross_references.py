"""Find claim sentences whose evidence lives somewhere the sentence does not name.

Claim 4 once said the values-question shares were "the closest agreement anywhere in this paper". It was true
when written and went false months later without anyone touching it, because claim 5 improved. The audit could
not catch it: every number in the sentence matched its table, and the thing that made the sentence wrong was a
different table entirely.

That is a class, not an incident. A sentence is exposed when its truth depends on a result it does not cite:
superlatives over the paper, rankings between claims, "the only", "unlike", "more than any". Each is a standing
bet on results that will keep moving until the submission.

This flags them for reading. It cannot judge them: whether "the one quantity that survives a change of
architecture" is still true takes a person comparing it against every other quantity. The point is to make the
list short and explicit rather than to trust that I will notice.

Out: results/CROSS_REFERENCES.md
"""
from __future__ import annotations

import re
import sys

from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "figures"))

ROOT = Path(__file__).resolve().parents[2]

# (pattern, why this sentence's truth depends on something it does not cite)
PATTERNS = [
    (r"\bclosest\b|\bnearest\b", "a superlative over other results"),
    (r"\b(largest|smallest|biggest|strongest|weakest|highest|lowest)\b", "a ranking against other results"),
    (r"\bthe only\b|\bthe one quantity\b|\bthe one thing\b", "an exclusivity claim over the rest of the paper"),
    (r"\banywhere in this paper\b|\bin this paper\b", "an explicit scope over the whole paper"),
    (r"\bmore than any\b|\bbetter than any\b|\bunlike any\b", "a comparison against an unnamed set"),
    (r"\bthe same (?:split|shape|pattern) (?:as|that)\b", "an asserted match with another result"),
    (r"\bwhich is the\b", "often introduces a ranking"),
    (r"\bbeside the (?:first|second|third|fourth|fifth) claim\b", "depends on another claim's current wording"),
    (r"\bfigures? \d\b", "depends on a figure that may be renumbered or rebuilt"),
]


def sentences(text):
    flat = " ".join(text.split())
    return [s.strip() for s in re.split(r"(?<=[.!?]) +", flat) if s.strip()]


def caption_blocks():
    """Each figure caption as (label, text). Captions carry more prose than the claims and are read as closely."""
    txt = open(f"{ROOT}/outputs/figures/paper/HERO_CAPTIONS.md").read()
    parts = re.split(r"^## (Figure \d+):", txt, flags=re.M)
    out = []
    for i in range(1, len(parts), 2):
        out.append((parts[i], parts[i + 1]))
    return out


def main():
    import build_pdf as B
    rows = []
    for n, (kind, title, body) in enumerate(B.CONTRIBUTIONS, 1):
        for s in sentences(body):
            hits = [why for pat, why in PATTERNS if re.search(pat, s, re.I)]
            if hits:
                rows.append((n, kind, title, s, hits))
    # captions were exempt from this sweep for no reason other than that I wrote it while reading claims
    for label, text in caption_blocks():
        for s in sentences(text):
            hits = [why for pat, why in PATTERNS if re.search(pat, s, re.I)]
            if hits:
                rows.append((label, "caption", label, s, hits))

    out = ["# Claim sentences whose truth depends on results they do not cite", "",
           "Generated by `analysis/cross_references.py`. These are not errors. They are the sentences that can go",
           "false without anyone editing them, because their evidence is elsewhere. Claim 4 carried one for weeks:",
           '"the closest agreement anywhere in this paper", true when written and false once claim 5 improved.', "",
           f"**{len(rows)} sentences flagged across {len(B.CONTRIBUTIONS)} claims and "
           f"{len(caption_blocks())} figure captions.**", ""]
    for n, kind, title, s, hits in rows:
        out.append(f"### {'claim ' + str(n) if kind != 'caption' else n} ({kind.lower()}): {title}")
        out.append("")
        out.append(f"> {s}")
        out.append("")
        out.append("flagged for: " + "; ".join(sorted(set(hits))))
        out.append("")
    open(f"{ROOT}/results/CROSS_REFERENCES.md", "w").write("\n".join(out) + "\n")
    print(f"[cross-refs] {len(rows)} sentences flagged in claims and captions")
    for n, kind, title, s, hits in rows:
        print(f"  {('claim ' + str(n)) if kind != 'caption' else n}: {s[:96]}...")
        print(f"            -> {'; '.join(sorted(set(hits)))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
