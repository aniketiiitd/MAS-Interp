"""Assemble the results write-up from the sources that are already audited, so it cannot drift from them.

The deliverable agreed on 2026-09-16 is frozen tables, all figures, and a detailed results write-up; the LaTeX is
the user's. The write-ups in results/ were last touched on 2026-09-17, before Gemma-4-E4B arrived and before three
claims were rewritten or retracted, so they describe a paper that no longer exists.

Writing a fresh one by hand would create a fourth artifact quoting numbers, alongside the claims, the abstract and
the captions -- and every one of those three has drifted from the tables at least once this campaign. So this
generates the body from the claims themselves (`figures/build_pdf.py: CONTRIBUTIONS`, which the audit checks
number by number) and the figure captions (`HERO_CAPTIONS.md`, likewise), and takes only the narrative sections
from a hand-written file. Regenerate it after any claim edit and the write-up follows automatically.

Hand-written narrative lives in results/RESULTS_NARRATIVE.md, split by `## <key>` headings.

Out: results/RESULTS.md
"""
from __future__ import annotations

import re
import sys
from datetime import datetime, timezone

from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "figures"))

ROOT = Path(__file__).resolve().parents[2]


def narrative():
    """Hand-written sections, keyed by heading. Missing file is fatal: a silent skip would ship a gutted document."""
    txt = open(f"{ROOT}/results/RESULTS_NARRATIVE.md").read()
    out, key, buf = {}, None, []
    for line in txt.splitlines():
        m = re.match(r"^## (\S+)\s*$", line)
        if m:
            if key:
                out[key] = "\n".join(buf).strip()
            key, buf = m.group(1), []
        elif key:
            buf.append(line)
    if key:
        out[key] = "\n".join(buf).strip()
    return out


def captions():
    """Figure headline + file, parsed from the captions the audit already checks."""
    txt = open(f"{ROOT}/outputs/figures/paper/HERO_CAPTIONS.md").read()
    figs = []
    for m in re.finditer(r"^## (Figure \d+): `([^`]+)`.*?\n\n\*\*(.+?)\*\*", txt, re.S | re.M):
        figs.append((m.group(1), m.group(2), " ".join(m.group(3).split())))
    return figs


def main():
    import build_pdf as B
    N = narrative()
    need = ["intro", "method", "retractions", "limits"]
    missing = [k for k in need if k not in N]
    if missing:
        raise SystemExit(f"[emit_results] RESULTS_NARRATIVE.md is missing sections: {missing}")

    main_claims = [c for c in B.CONTRIBUTIONS if c[0] == "MAIN"]
    supp = [c for c in B.CONTRIBUTIONS if c[0] != "MAIN"]
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    L = [f"# MAD-Interp: results", "",
         f"Generated {stamp} by `analysis/emit_results.py` from the claims and captions that "
         f"`analysis/audit_reported.py` verifies number by number. Do not edit this file; edit the claims in "
         f"`figures/build_pdf.py`, the captions in `outputs/figures/paper/HERO_CAPTIONS.md`, or the narrative in "
         f"`results/RESULTS_NARRATIVE.md`, then regenerate.", "",
         N["intro"], "", "## Method", "", N["method"], "",
         f"## Findings", "",
         f"{len(main_claims)} main and {len(supp)} supporting. Every number below is checked against a table by "
         f"the audit; `results/NUMBERS.md` lists each one with the table it comes from.", ""]

    for i, (kind, title, body) in enumerate(B.CONTRIBUTIONS, 1):
        L += [f"### {i}. {title}", "", f"*{kind.lower()}*", "", " ".join(body.split()), ""]

    L += ["## Figures", ""]
    for name, fn, headline in captions():
        L += [f"**{name}** (`{fn}`) — {headline}", ""]
    L += ["Full captions, with every number, are in `outputs/figures/paper/HERO_CAPTIONS.md`.", "",
          "## What was retracted, and why", "", N["retractions"], "",
          "## Limits", "", N["limits"], ""]

    open(f"{ROOT}/results/RESULTS.md", "w").write("\n".join(L) + "\n")
    print(f"[done] results/RESULTS.md: {len(B.CONTRIBUTIONS)} claims, {len(captions())} figures, "
          f"{len(N)} narrative sections")
    return 0


if __name__ == "__main__":
    sys.exit(main())
